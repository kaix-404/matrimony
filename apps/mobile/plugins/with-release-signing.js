const { withAppBuildGradle } = require('expo/config-plugins');

/**
 * Signs release builds with the Google Play upload key.
 *
 * Expo's template build.gradle signs the release build type with the generated
 * debug keystore, which is fine for sideloading and useless for Play: an upload
 * signed with it is rejected, and if it were accepted it would lock the app to a
 * certificate nobody controls. The key itself must never be in this repository,
 * so this plugin only adds the wiring: gradle reads
 * MATRIMONY_UPLOAD_KEYSTORE_PATH, MATRIMONY_UPLOAD_KEYSTORE_PASSWORD,
 * MATRIMONY_UPLOAD_KEY_ALIAS and MATRIMONY_UPLOAD_KEY_PASSWORD from the
 * environment (CI secrets) or from gradle properties of the same names, and
 * fails instead of packaging a release bundle when they are absent.
 *
 * This is a config plugin rather than an edit to `android/` because prebuild
 * regenerates that directory, so a hand edit would survive exactly until the
 * next build.
 */

const MARKER = '@generated by plugins/with-release-signing';

const SIGNING_DEFS = `
// --- Upload-key signing: ${MARKER} ---
//
// Release bundles are signed with the Play upload key. It is deliberately not
// in this repository: CI decodes it from a repository secret and exports these
// variables, and a local release build can export the same names or pass them
// as -PMATRIMONY_... gradle properties.
def uploadKeystorePath = System.getenv("MATRIMONY_UPLOAD_KEYSTORE_PATH") ?: findProperty("MATRIMONY_UPLOAD_KEYSTORE_PATH")
def uploadKeystorePassword = System.getenv("MATRIMONY_UPLOAD_KEYSTORE_PASSWORD") ?: findProperty("MATRIMONY_UPLOAD_KEYSTORE_PASSWORD")
def uploadKeyAlias = System.getenv("MATRIMONY_UPLOAD_KEY_ALIAS") ?: findProperty("MATRIMONY_UPLOAD_KEY_ALIAS")
def uploadKeyPassword = System.getenv("MATRIMONY_UPLOAD_KEY_PASSWORD") ?: findProperty("MATRIMONY_UPLOAD_KEY_PASSWORD")
def uploadKeyReady = [uploadKeystorePath, uploadKeystorePassword, uploadKeyAlias, uploadKeyPassword].every { it }
`;

const SIGNING_CONFIGS_ANCHOR = `    signingConfigs {
        debug {
            storeFile file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }
    }`;

const SIGNING_CONFIGS = `    signingConfigs {
        debug {
            storeFile file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }
        release {
            // Filled in only when the upload key is configured, which is what
            // React Native documents. Declaring the config unconditionally keeps
            // the buildTypes block below a plain reference; an unfilled config is
            // never used for signing, because the guard further down refuses to
            // package a release without the key.
            if (uploadKeyReady) {
                storeFile file(uploadKeystorePath)
                // Stated rather than inferred from the file extension: the key is
                // PKCS#12, and a JKS assumption on it fails with a password error
                // that says nothing about the real cause.
                storeType "PKCS12"
                storePassword uploadKeystorePassword
                keyAlias uploadKeyAlias
                keyPassword uploadKeyPassword
            }
        }
    }`;

const RELEASE_ANCHOR = `            // Caution! In production, you need to generate your own keystore file.
            // see https://reactnative.dev/docs/signed-apk-android.
            signingConfig signingConfigs.debug`;

const RELEASE_SIGNING = `            // The debug keystore is never used for a release bundle: Play
            // rejects it outright, and one that got through would pin the app to
            // a certificate nobody controls. The guard below turns a missing
            // upload key into a clear failure instead of an unsigned bundle.
            signingConfig signingConfigs.release`;

const DEPENDENCIES_ANCHOR = `dependencies {
    // The version of react-native is set by the React Native Gradle Plugin`;

const SIGNING_GUARD = `// Refuse to package a release bundle that is not signed with the upload key.
// Reading the task graph instead of the requested task names leaves
// assembleDebug, an IDE sync and configuration-only invocations alone, while
// bundleRelease and assembleRelease fail with the reason here rather than
// succeeding into an artifact Play will reject.
gradle.taskGraph.whenReady { graph ->
    def packagingRelease = graph.allTasks.any { task ->
        task.project == project && task.name in ["bundleRelease", "assembleRelease", "packageReleaseBundle", "packageRelease"]
    }
    if (packagingRelease && !uploadKeyReady) {
        throw new GradleException(
                "Release bundles must be signed with the Play upload key, but MATRIMONY_UPLOAD_KEYSTORE_PATH, MATRIMONY_UPLOAD_KEYSTORE_PASSWORD, MATRIMONY_UPLOAD_KEY_ALIAS and MATRIMONY_UPLOAD_KEY_PASSWORD are not all set (environment variables or gradle properties). Google Play does not accept a debug-signed bundle.")
    }
}

${DEPENDENCIES_ANCHOR}`;

/**
 * Replaces `anchor` with `replacement` exactly once, naming what changed so a
 * template rewrite in a future Expo SDK is reported here rather than surfacing
 * as a bundle quietly signed with the debug key.
 */
function replaceOnce(contents, anchor, replacement, description) {
  const occurrences = contents.split(anchor).length - 1;

  if (occurrences === 0) {
    throw new Error(
      `withReleaseSigning: could not find ${description} in android/app/build.gradle. The Expo SDK 57 template is expected to contain it; release signing has to be re-applied by hand to the new template before a bundle is built.`,
    );
  }
  if (occurrences > 1) {
    throw new Error(
      `withReleaseSigning: found ${description} ${occurrences} times in android/app/build.gradle, so it is ambiguous which one to replace.`,
    );
  }

  return contents.replace(anchor, replacement);
}

function applyReleaseSigning(contents) {
  if (contents.includes(MARKER)) {
    return contents;
  }

  // Inserted before `android {` so the variables exist when the signing config
  // and build type blocks are evaluated.
  let next = replaceOnce(
    contents,
    '\nandroid {\n    ndkVersion rootProject.ext.ndkVersion',
    `${SIGNING_DEFS}\nandroid {\n    ndkVersion rootProject.ext.ndkVersion`,
    'the start of the `android {}` block',
  );

  next = replaceOnce(
    next,
    SIGNING_CONFIGS_ANCHOR,
    SIGNING_CONFIGS,
    'the `signingConfigs` block with the debug keystore',
  );

  next = replaceOnce(
    next,
    RELEASE_ANCHOR,
    RELEASE_SIGNING,
    'the release build type signing the bundle with the debug keystore',
  );

  next = replaceOnce(next, DEPENDENCIES_ANCHOR, SIGNING_GUARD, 'the `dependencies` block');

  return next;
}

module.exports = function withReleaseSigning(config) {
  return withAppBuildGradle(config, (config) => {
    if (config.modResults.language !== 'groovy') {
      throw new Error(
        'withReleaseSigning: android/app/build.gradle is not Groovy, so the release signing wiring cannot be added.',
      );
    }

    config.modResults.contents = applyReleaseSigning(config.modResults.contents);

    return config;
  });
};

module.exports.applyReleaseSigning = applyReleaseSigning;
